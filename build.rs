//! Embeds `assets/icon.ico` and a VERSIONINFO block into the executable, so
//! Explorer, the taskbar and the "Properties" dialog show the real product
//! instead of a generic binary.
//!
//! Uses the resource compiler from the Windows SDK directly; when it is not
//! installed the build still succeeds, only without the embedded resources.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let icon = manifest.join("assets").join("icon.ico");
    println!("cargo:rerun-if-changed={}", icon.display());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=TRAFFICDESK_RC");

    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    if !icon.is_file() {
        println!("cargo:warning=assets/icon.ico is missing; building without an icon");
        return;
    }

    let version = std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    let (major, minor, patch) = split_version(&version);
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));
    // rc.exe treats `\` inside a string as an escape, so a Windows path has to
    // be written with doubled separators or the drive letters disappear.
    let icon_literal = icon.display().to_string().replace('\\', "\\\\");

    let rc_text = format!(
        r#"// Generated by build.rs: application icon and version information.
1 ICON "{icon}"
1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEOS 0x40004L
FILETYPE 0x1L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "TrafficDesk"
      VALUE "FileDescription", "TrafficDesk - floating Windows network traffic monitor"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "trafficdesk"
      VALUE "OriginalFilename", "trafficdesk.exe"
      VALUE "ProductName", "TrafficDesk"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        icon = icon_literal,
        major = major,
        minor = minor,
        patch = patch,
        version = version,
    );

    let rc_file = out_dir.join("trafficdesk.rc");
    let res_file = out_dir.join("trafficdesk.res");
    if std::fs::write(&rc_file, rc_text).is_err() {
        println!("cargo:warning=could not write the resource script; building without an icon");
        return;
    }

    let Some(rc) = find_rc() else {
        println!("cargo:warning=rc.exe not found (Windows SDK); building without an icon");
        return;
    };

    match Command::new(&rc)
        .arg("/nologo")
        .arg("/fo")
        .arg(&res_file)
        .arg(&rc_file)
        .output()
    {
        Ok(output) if output.status.success() => {
            println!("cargo:rustc-link-arg={}", res_file.display());
        }
        Ok(output) => {
            // rc.exe prints its diagnostics on stdout, not stderr.
            let stdout = String::from_utf8_lossy(&output.stdout);
            let stderr = String::from_utf8_lossy(&output.stderr);
            let detail = format!("{} {}", stdout.trim(), stderr.trim());
            println!(
                "cargo:warning=rc.exe failed ({}); building without an icon",
                detail.trim()
            );
        }
        Err(e) => println!("cargo:warning=could not run rc.exe ({e}); building without an icon"),
    }
}

/// `1.2.3` and `1.2` both have to produce four numbers for VERSIONINFO.
fn split_version(version: &str) -> (u32, u32, u32) {
    let mut parts = version.split('.').map(|p| p.parse::<u32>().unwrap_or(0));
    (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    )
}

/// `rc.exe` lives under the Windows Kits install; `TRAFFICDESK_RC` overrides.
fn find_rc() -> Option<PathBuf> {
    if let Some(explicit) = std::env::var_os("TRAFFICDESK_RC") {
        let path = PathBuf::from(explicit);
        if path.is_file() {
            return Some(path);
        }
    }
    let arch = match std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
        Ok("aarch64") => "arm64",
        Ok("x86") => "x86",
        _ => "x64",
    };
    let mut roots: Vec<PathBuf> = Vec::new();
    for var in ["WindowsSdkDir", "WindowsSdkVerBinPath"] {
        if let Some(dir) = std::env::var_os(var) {
            let dir = PathBuf::from(dir);
            roots.push(dir.join("bin"));
            roots.push(dir);
        }
    }
    roots.push(PathBuf::from(r"C:\Program Files (x86)\Windows Kits\10\bin"));

    for root in roots {
        let Ok(entries) = std::fs::read_dir(&root) else {
            continue;
        };
        let mut versions: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| {
                p.is_dir()
                    && p.file_name()
                        .is_some_and(|n| n.to_string_lossy().starts_with("10."))
            })
            .collect();
        // Newest SDK first.
        versions.sort();
        for version in versions.into_iter().rev() {
            if let Some(found) = rc_in(&version.join(arch)) {
                return Some(found);
            }
        }
        // Some layouts place rc.exe straight under the root or the host folder.
        for candidate in [root.join("rc.exe"), root.join(arch).join("rc.exe")] {
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}

fn rc_in(dir: &Path) -> Option<PathBuf> {
    let candidate = dir.join("rc.exe");
    candidate.is_file().then_some(candidate)
}
